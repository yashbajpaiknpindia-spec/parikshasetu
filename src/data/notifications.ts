/** Best official links for an exam: prefer the apply/notice deep links from its
 *  notification entries, falling back to nothing (callers fall back to the homepage). */
export function portalLinksFor(examSlug: string): { applyUrl?: string; noticeUrl?: string } {
  const withLinks = notifications.filter((n) => n.examSlug === examSlug && (n.applyUrl || n.noticeUrl));
  return {
    applyUrl: withLinks.find((n) => n.applyUrl)?.applyUrl,
    noticeUrl: withLinks.find((n) => n.noticeUrl)?.noticeUrl,
  };
}

